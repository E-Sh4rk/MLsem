(* Types of variables and calls, as plain data for hover and highlighting.

   A definition is checked once per derivation (one per [val] line, if any),
   and [Main] keeps each derivation; [Annotations] reads from it the type of
   every variable occurrence, binder and call. This module turns those into
   plain data (byte ranges, strings, integers) that the supervisor keeps and
   answers from, without the engine.

   Type variables are identified by integers, assigned per document. The
   builder shares variable objects by name, so ['a] in two [val] lines can be
   one variable: highlighting matches by this identity, within one
   definition. Only rigid variables (written by the user) get ids: those are
   the ones a [val] line can show. *)

open Mlsem_common
open Mlsem_types
open Mlsem_app

(* A variable occurrence or binder, with what its hover shows: a single type,
   or, when derivations differ, one row per derivation (type and the [val]
   signature it was checked against) followed by their union. *)
type overload_row = {
  row_type: string option;  (** [None]: this derivation never reaches the node *)
  sig_text: string option;
  sig_range: (int * int) option;  (** the [val] line, to colour in the editor *)
}

type hover_body =
  | Type of string
  (* A hole of a draft [val] line, as written ([_] or ['_a]), and the type it
     was resolved to. *)
  | Hole of {
      hole: string;
      value: string;
    }
  (* A hole of a line whose check gave several overloads, which disagree on
     it: per overload, its value ([None]: the line cannot be that overload). *)
  | Hole_per_overload of {
      hole: string;
      rows: (string * string option) list;
    }
  | Overloads of {
      rows: overload_row list;
      union: string;
    }

type hover = {
  h_start: int;
  h_end: int;
  body: hover_body;
}

(* An occurrence of a type variable in a [val] line. *)
type tvar_occ = {
  o_start: int;
  o_end: int;
  tvar: int;
}

(* Something in a definition's body whose type mentions type variables: a
   variable occurrence or binder, a call argument, or a whole call. *)
type mark = {
  m_start: int;
  m_end: int;
  tvars: int list;
}

type defn = {
  tvar_occs: tvar_occ list;
  marks: mark list;
}

(* A call site [f a1 ... an]. [group] is shared by the calls of the same
   callee whose argument types are equivalent. *)
type call = {
  c_start: int;
  c_end: int;
  callee: (string * int) option;  (** name and definition offset *)
  sig_index: int option;
  args: (int * int * string) list;
  result: string;
  instance: (string * string) list;  (** callee's type variable := type *)
  instances: (int * (string * string) list) list;
    (** for a top-level callee: per overload of its signature (by index), the
      instance of that overload the call fits, as the overload's variable :=
      type; overloads the call does not fit are absent *)
  group: int;
}

(* Where a variable is bound or used, for highlighting its occurrences. [var]
   identifies the variable within the document. *)
type occ = {
  v_start: int;
  v_end: int;
  var: int;
  binder: bool;
}

(* A change of a callee's [val] lines for a call to it that fails:
   [x_start, x_end] is the call, [edits] the byte intervals to replace and
   their new text. *)
type fix = {
  x_start: int;
  x_end: int;
  title: string;
  edits: (int * int * string) list;
}

type t = {
  hovers: hover list;
  defns: defn list;
  calls: call list;
  occs: occ list;
  fixes: fix list;
}

let empty = {hovers = []; defns = []; calls = []; occs = []; fixes = []}

let range pos =
  if pos = Position.dummy then
    None
  else
    Some
      ( Position.offset (Position.start_of_position pos),
        Position.offset (Position.end_of_position pos) )

let lex_range ((s, e) : Lexing.position * Lexing.position) = (s.pos_cnum, e.pos_cnum)

(* What the editor tooling needs from the parsed program. *)
type source = {
  sigs: ((int * int) * TyExpr.t) list;
    (** a [val] line's range and its type, as written (with locations) *)
  params: ((int * int) * (int * int) option list) list;
    (** a definition's name and its parameters' names, in order; [None]
          for a parameter that is a pattern *)
  uses: (int * int, unit) Hashtbl.t;
    (** variable occurrences written in the source, as opposed to ones
          generated by desugaring *)
}

let children : PAst.pexpr -> PAst.pexpr list =
 fun (_, e) ->
  match e with
  | Magic _
  | Const _
  | Var _
  | Enum _
  | Break
  | Continue ->
      []
  | NoGen e
  | Tag (_, e)
  | TagProj (e, _)
  | Suggest (_, _, e)
  | Lambda (_, _, e)
  | Declare (_, e)
  | TupleProj (e, _, _)
  | Hd e
  | Tl e
  | RecordProj (e, _)
  | TypeCast (e, _, _)
  | TypeCoerce (e, _, _)
  | VarAssign (_, e)
  | Return e ->
      [e]
  | LambdaRec l -> List.map (fun (_, _, e) -> e) l
  | Ite (e, _, e1, e2) -> [e; e1; e2]
  | App (a, b)
  | Let (_, a, b)
  | Cons (a, b)
  | Seq (a, b)
  | While (a, _, b) ->
      [a; b]
  | Tuple es
  | Alt es ->
      es
  | Record l -> List.map snd l
  | RecordUpdate (a, _, b) -> a :: Option.to_list b
  | PatMatch (e, l) -> e :: List.map snd l
  | Cond (e, _, e1, e2) -> e :: e1 :: Option.to_list e2

(* The parameters of a definition: its leading lambdas. A parameter that is a
   pattern is a lambda on a placeholder matched right away; when the pattern
   is a variable ([(x : t)]), that variable is the parameter. *)
let rec params_of ((_, e) : PAst.pexpr) =
  match e with
  | Lambda (name, _, body) -> (
      match (range (Position.position name), body) with
      | Some r, _ -> Some r :: params_of body
      | None, (_, PatMatch (_, [(PatVar (_, name), body)])) ->
          range (Position.position name) :: params_of body
      | None, (_, PatMatch (_, [(_, body)])) -> None :: params_of body
      | None, _ -> None :: params_of body )
  | _ -> []

let source (program : PAst.program) =
  let uses = Hashtbl.create 64 in
  let rec collect_uses ((_, e) as pe : PAst.pexpr) =
    ( match e with
    | Var name -> Option.iter (fun r -> Hashtbl.replace uses r ()) (range (Position.position name))
    | _ -> () ) ;
    List.iter collect_uses (children pe)
  in
  let sigs, params =
    List.fold_left
      (fun (sigs, params) (annot, elem) ->
         match (elem : PAst.element) with
         | SigDef (_, _, ty) -> (
             match range (Position.position annot) with
             | Some r -> ((r, ty) :: sigs, params)
             | None -> (sigs, params) )
         | Definitions defs ->
             List.fold_left
               (fun (sigs, params) (_, (_, name), e) ->
                  collect_uses e ;
                  match range (Position.position name) with
                  | Some r -> (sigs, (r, params_of e) :: params)
                  | None -> (sigs, params) )
               (sigs, params) defs
         | _ -> (sigs, params) )
      ([], []) program
  in
  {sigs; params; uses}

(* Per-document state while converting. *)
type ctx = {
  src: source;
  mutable tvar_ids: (TVar.t * int) list;
  mutable groups: ((string * int) option * GTy.t list * int) list;
  mutable var_ids: (Variable.t * int) list;
  mutable occs: occ list;
  mutable sigs: (Variable.t * Signature.t) list;  (** top-level definitions so far *)
  mutable acc: t;
}

let create program =
  {
    src = source program;
    tvar_ids = [];
    groups = [];
    var_ids = [];
    occs = [];
    sigs = [];
    acc = empty;
  }

(* A node is typed once per derivation, and some several times in one. *)
let finish ctx = {ctx.acc with occs = List.sort_uniq compare ctx.occs}

let var_id ctx v =
  match List.find_opt (fun (v', _) -> Variable.equal v v') ctx.var_ids with
  | Some (_, i) -> i
  | None ->
      let i = List.length ctx.var_ids in
      ctx.var_ids <- (v, i) :: ctx.var_ids ;
      i

let occ ctx ~binder v (v_start, v_end) =
  ctx.occs <- {v_start; v_end; var = var_id ctx v; binder} :: ctx.occs

let tvar_id ctx v =
  match List.find_opt (fun (v', _) -> TVar.equal v v') ctx.tvar_ids with
  | Some (_, i) -> i
  | None ->
      let i = List.length ctx.tvar_ids in
      ctx.tvar_ids <- (v, i) :: ctx.tvar_ids ;
      i

let tvar_ids ctx ty =
  GTy.fv ty |> MVarSet.proj1 |> TVarSet.elements
  |> List.filter (TVar.has_kind KNoInfer)
  |> List.map (tvar_id ctx)
  |> List.sort_uniq compare

let var_name v = TVar.prefix v ^ TVar.name v

(* The range of a variable occurrence, if it is written in the source:
   desugaring (pattern matching, loops, mutable variables) generates
   occurrences that either have no location or point at something else. *)
let use_range ctx pos =
  Option.bind (range pos) (fun r -> if Hashtbl.mem ctx.src.uses r then Some r else None)

(* Where the name of a bound variable is written. *)
let binder_range v = range (Variable.get_name_location v)

let rec tyexpr_children : TyExpr.t -> TyExpr.t list = function
  | TDyn
  | TVar _
  | TRowVar _
  | TBase _
  | TEnum _
  | TCustom _ ->
      []
  | TApp (_, ts)
  | TTuple ts ->
      ts
  | TTag (_, t)
  | TOption t
  | TNeg t
  | TRecProj (t, _)
  | TTagProj (t, _)
  | TLoc (_, t) ->
      [t]
  | TRecord (fields, tail) -> tail :: List.map snd fields
  | TSList re -> regexp_children re
  | TCons (a, b)
  | TArrow (a, b)
  | TCup (a, b)
  | TCap (a, b)
  | TDiff (a, b) ->
      [a; b]
  | TWhere (t, defs) -> t :: List.map (fun (_, _, t) -> t) defs
  | TRecUpd (t, fields) -> t :: List.map snd fields

and regexp_children : TyExpr.regexp -> TyExpr.t list = function
  | Epsilon -> []
  | Symbol t -> [t]
  | Union rs
  | Concat rs ->
      List.concat_map regexp_children rs
  | Star r
  | Plus r
  | Option r ->
      regexp_children r

(* Located type variables written in [ty]. *)
let rec tyexpr_tvars (ty : TyExpr.t) =
  match ty with
  | TLoc (loc, TVar (_, name)) -> [(lex_range loc, name)]
  | _ -> List.concat_map tyexpr_tvars (tyexpr_children ty)

(* The type written in the [val] line at [r]. *)
let sig_type ctx r = List.assoc_opt r ctx.src.sigs

(* Located holes of a draft [val] line: its weak type variables, written [_]
   (named [_holeN] by the parser) or ['_a]. *)
let rec tyexpr_holes (ty : TyExpr.t) =
  match ty with
  | TLoc (loc, TVar (KInfer, name)) -> [(lex_range loc, name)]
  | _ -> List.concat_map tyexpr_holes (tyexpr_children ty)

(* A tuple is printed without parentheses; written in place of a variable, it
   needs them. *)
let paren_tuple value =
  if String.contains value ',' && value.[0] <> '(' then "(" ^ value ^ ")" else value

(* The signature of a written type. Building a parametric alias ([t('a)])
   reads the printing aliases, which [Main] provides per element; outside
   it they come from [envs]. *)
let build_signature envs t =
  let benv, _, _, _, penv = envs in
  PEnv.sequential_handler penv (Signature.build benv) t |> fst

(* The holes of a draft's [val] lines (at [locs]), solved from the
   definition's type scheme [ty].

   The definition has every line's type with the holes filled, so each line
   [Lᵢ] is above an instance of [ty]: [ty₁ ≤ L₁, …, tyₙ ≤ Lₙ] is tallied,
   each [tyᵢ] a copy of [ty] whose variables are solved for, the holes
   shared by the lines, and the lines' type variables fixed (a line's ['a]
   is any type; ['a] in two lines is two variables, as in MLsem). Tally
   gives the most general solutions, possibly several: a hole in a domain
   can have values that each give a part of [ty] ([h -> h] for
   [(int -> int) & (bool -> bool)]: [int], and [bool]). MLsem itself may
   have instantiated the holes several ways and intersected the results, so
   its solving is not read back: a solution here need not be one of its.

   Per solution: each hole as [(range, shown, value, line index)], and each
   line filled with it. *)
let draft_solutions ctx envs display ty locs =
  let weak_of t =
    TVOp.vars t |> MVarSet.proj1 |> TVarSet.elements |> List.filter (TVar.has_kind KInfer)
  in
  let rigid_of t =
    TVOp.vars t |> MVarSet.proj1 |> TVarSet.elements
    |> List.filter (fun v -> not (TVar.has_kind KInfer v))
  in
  (* Each line's rigid variables are its own (['a] in two lines is two
     variables, as in MLsem), copies with the same names; the holes are
     shared. *)
  let lines =
    List.filter_map
      (fun r ->
         Option.map
           (fun t ->
              let l = build_signature envs t |> fst |> Signature.to_gty |> GTy.ub in
              let own =
                rigid_of l
                |> List.map (fun v -> (v, TVar.typ (TVar.mk KNoInfer (Some (TVar.name v)))))
                |> Subst.of_list1
              in
              (t, Subst.apply own l) )
           (sig_type ctx r) )
      locs
  in
  let d = Ty.conj (List.map snd lines) in
  let tvs, o = TyScheme.get ty in
  let o = GTy.ub o in
  (* A variable of the definition's type that is not generalized is one
     type: fixed, like the lines' own. *)
  let o =
    let w =
      TVOp.vars o |> MVarSet.proj1
      |> TVarSet.filter (fun v ->
        TVar.has_kind KInfer v && not (TVarSet.mem v (MVarSet.proj1 tvs)) )
    in
    Subst.apply (TVOp.refresh ~kind:KNoInfer (MVarSet.of_set1 w)) o
  in
  (* The holes: the lines' weak variables. *)
  let weak = weak_of d in
  let cs = List.map (fun (_, l) -> (Subst.apply (TVOp.refresh ~kind:KInfer tvs) o, l)) lines in
  (* The variables a solution leaves in the lines are made rigid ones taken
     from one pool: the i-th of any solution is the pool's i-th, so that two
     solutions that differ only by these variables give equal lines. *)
  let pool = Hashtbl.create 8 in
  let pooled i =
    match Hashtbl.find_opt pool i with
    | Some v -> v
    | None ->
        let v = TVar.mk KNoInfer None in
        Hashtbl.add pool i v ; v
  in
  TVOp.tally (TVOp.all_vars KNoInfer) cs
  |> List.filter_map (fun s ->
    (* A solution can leave weak variables, the holes' own among them
             ([_hole := ('a & int) | (_hole \ int)] when the hole is
             intersected with [int]). Any choice for them is a solution, but
             one choice for all the lines, so that the holes agree:
             - those in the lines are chosen by their polarity in them, as
               when simplifying a signature ([empty] where only positive, so
               a result is the tightest; [any] where only negative, so a
               domain is the widest); one there both ways is a variable of the
               signature, made a rigid one of the pool;
             - those not in the lines do not change them: [empty]. *)
    let mono = TVOp.all_vars KNoInfer in
    let clean =
      TVOp.clean_subst' ~pos1:Ty.empty ~neg1:Ty.any ~pos2:Row.empty ~neg2:Row.any mono
        [Subst.apply s d]
    in
    let line = Subst.apply clean (Subst.apply s d) in
    let rigid = weak_of line |> List.mapi (fun i v -> (v, TVar.typ (pooled i))) |> Subst.of_list1 in
    let resolve t = Subst.apply rigid (Subst.apply clean (Subst.apply s t)) in
    let rest =
      List.concat_map (fun v -> weak_of (resolve (TVar.typ v))) weak
      |> List.sort_uniq TVar.compare
      |> List.map (fun w -> (w, Ty.empty))
      |> Subst.of_list1
    in
    let resolve t = Subst.apply rest (resolve t) in
    (* Kept if each line, filled, is above its instance: the instances'
       variables left are any choice, [empty] here. *)
    let holds (oi, l) =
      let oi = resolve oi in
      let left = weak_of oi |> List.map (fun w -> (w, Ty.empty)) |> Subst.of_list1 in
      Ty.leq (Subst.apply left oi) (resolve l)
    in
    (* Per line: the variables the solution leaves that are not the line's
       own, named ['a], ['b], ... skipping the line's own names. *)
    let final l =
      let own = rigid_of l in
      let taken = List.map TVar.name own in
      let others =
        rigid_of (resolve l) |> List.filter (fun v -> not (List.exists (TVar.equal v) own))
      in
      let names =
        List.init 26 (fun i -> String.make 1 (Char.chr (Char.code 'a' + i)))
        |> List.filter (fun n -> not (List.mem n taken))
      in
      let rename =
        List.filteri (fun i _ -> i < List.length names) others
        |> List.mapi (fun i v -> (v, TVar.typ (TVar.mk KNoInfer (Some (List.nth names i)))))
        |> Subst.of_list1
      in
      fun t -> resolve t |> Subst.apply rename
    in
    if not (List.for_all holds cs) then
      None
    else
      let holes =
        List.concat
          (List.mapi
             (fun i (t, l) ->
                let final = final l in
                List.filter_map
                  (fun (range, name) ->
                     List.find_opt (fun v -> TVar.name v = name) weak
                     |> Option.map (fun v ->
                       let shown =
                         if String.starts_with ~prefix:"_hole" name then "_" else "'" ^ name
                       in
                       let value = final (TVar.typ v) |> GTy.mk |> display |> paren_tuple in
                       (range, shown, value, i) ) )
                  (tyexpr_holes t) )
             lines )
      in
      Some
        (holes, List.map (fun (_, l) -> final l l) lines, List.map (fun (_, l) -> resolve l) lines) )
  (* Only the most precise solutions, in two passes:
     - one strictly wider than another, or equivalent to an earlier one, is
       dropped ([empty] in a domain fits any function). Done first: two
       solutions each exact on one line only, and junk on the other, imply
       together the one exact on both, which must stay;
     - then a set of solutions that together imply each dropped one
       ([~bool -> int] is implied by [int -> int] and
       [~(int | bool) -> 42]), none implied by the others of the set. It is
       grown from the solutions with the narrowest domain to those with the
       widest, a solution added only if the set does not already imply it,
       so that the precise overloads come first ([int -> int] before
       [int | 'a -> int | 'a]); then, from the last added, one implied by
       the rest of the set is dropped. Checking against the set only, not
       against all the others, keeps each check small: a tally with many
       arrows does not end in time. A filled line is polymorphic, so the
       set's lines may be instantiated ([int | 'a -> int | 'a] implies
       [int -> int]): a tally, after a plain subtyping check. The first pass
       must come before it: tallying the junk of mixed solutions (recursive
       types) does not end in time.
     The kept solutions are in tally's order. *)
  |> fun sols ->
  let conj (_, _, f) = Ty.conj f in
  let sols =
    List.filteri
      (fun i s ->
         let f = conj s in
         not
           ( List.exists
               (fun s' ->
                  let f' = conj s' in
                  Ty.leq f' f && not (Ty.leq f f') )
               sols
           || List.exists
                (fun s' ->
                   let f' = conj s' in
                   Ty.leq f' f && Ty.leq f f' )
                (List.filteri (fun j _ -> j < i) sols) ) )
      sols
  in
  let sols = Array.of_list sols in
  let n = Array.length sols in
  let filled i =
    let _, _, f = sols.(i) in
    f
  in
  (* Each filled line is polymorphic: the solutions [set] imply solution [i]
     if instances of their lines, each its own, are below [i]'s, whose
     variables are fixed. *)
  let implies set i =
    let f = Ty.conj (filled i) in
    let others = List.concat_map filled set in
    let instance l = Subst.apply (TVOp.refresh ~kind:KInfer (TVOp.vars l)) l in
    others <> []
    && ( Ty.leq (Ty.conj others) f
       || TVOp.tally (TVOp.all_vars KNoInfer) [(Ty.conj (List.map instance others), f)] <> [] )
  in
  (* The domain of a solution's filled lines, [any] if they are not a
     function. *)
  let dom =
    Array.init n (fun i ->
      let t = Ty.conj (filled i) in
      if Ty.leq t Arrow.any then Arrow.domain t else Ty.any )
  in
  (* Narrowest first: by how many domains are strictly below it. *)
  let narrower i =
    List.init n Fun.id
    |> List.filter (fun j -> Ty.leq dom.(j) dom.(i) && not (Ty.leq dom.(i) dom.(j)))
    |> List.length
  in
  let order =
    List.init n (fun i -> (narrower i, i))
    |> List.stable_sort (fun (a, _) (b, _) -> compare a b)
    |> List.map snd
  in
  let grown = List.fold_left (fun set i -> if implies set i then set else set @ [i]) [] order in
  let kept =
    List.fold_right
      (fun i set ->
         let rest = List.filter (( <> ) i) set in
         if implies rest i then rest else set )
      grown grown
  in
  Array.to_list sols
  |> List.filteri (fun i _ -> List.mem i kept)
  |> List.map (fun (holes, lines, _) -> (holes, lines))

(* The hovers of a draft's holes, from its [solutions]: a hole has a value if
   every solution gives it the same; otherwise its hover lists the value per
   solution, next to its line filled by that solution, and it cannot be
   filled. *)
let draft_hole_hovers display solutions =
  match solutions with
  | [] -> []
  | (holes, _) :: _ ->
      List.mapi
        (fun k ((h_start, h_end), hole, _, i) ->
           let values =
             List.map (fun (hs, _) -> (fun (_, _, v, _) -> v) (List.nth hs k)) solutions
           in
           let body =
             match List.sort_uniq compare values with
             | [value] -> Hole {hole; value}
             | _ ->
                 Hole_per_overload
                   {
                     hole;
                     rows =
                       List.map2
                         (fun (_, lines) v -> (display (GTy.mk (List.nth lines i)), Some v))
                         solutions values;
                   }
           in
           {h_start; h_end; body} )
        holes

(* The instance of [overload] a call with these argument and result types
   uses: a value for each of the overload's variables such that the
   instantiated overload is a subtype of the call's type ([args] to
   [result]), as an application requires. [None] when there is none, or when
   the overload has no variable. Of the instances, the one closest to the
   call: the variables the call leaves open are [any] where the instantiated
   overload gives them out and [empty] where it takes them in; the rest are
   [empty]. *)
let call_instance overload args result =
  let o = Signature.to_gty overload |> GTy.ub in
  let vars = TVOp.vars o |> MVarSet.proj1 |> TVarSet.elements in
  if vars = [] then
    None
  else
    let call = List.fold_right (fun a acc -> Arrow.mk (GTy.lb a) acc) args (GTy.lb result) in
    (* Everything but the overload's variables is fixed, the caller's
       variables included. *)
    let mono =
      MVarSet.diff (MVarSet.union (TVOp.all_vars KNoInfer) (TVOp.all_vars KInfer)) (TVOp.vars o)
    in
    match TVOp.tally ~record:false mono [(o, call)] with
    | [] -> None
    | s :: _ ->
        let inst = Subst.apply s o in
        let clean =
          TVOp.clean_subst' ~pos1:Ty.any ~neg1:Ty.empty ~pos2:Row.any ~neg2:Row.empty mono [inst]
        in
        let open_vars t =
          MVarSet.diff (TVOp.vars t) mono
          |> MVarSet.proj1 |> TVarSet.elements
          |> List.map (fun v -> (v, Ty.empty))
          |> Subst.of_list1
        in
        let rest = open_vars (Subst.apply clean inst) in
        let value v =
          let t = Subst.apply clean (Subst.apply s (TVar.typ v)) in
          Subst.apply (open_vars t) (Subst.apply rest t)
        in
        let inst = Subst.of_list1 (List.map (fun v -> (v, value v)) vars) in
        if Ty.leq (Subst.apply inst o) call then
          Some (List.map (fun v -> (v, value v)) vars)
        else
          None

let is_tvar ty =
  match TVOp.vars ty |> MVarSet.proj1 |> TVarSet.elements with
  | [v] -> Ty.leq ty (TVar.typ v) && Ty.leq (TVar.typ v) ty
  | _ -> false

(* Occurrences of the overload's type variables in its [val] line. *)
let val_tvar_occs ctx overload r =
  let vars = GTy.fv overload |> MVarSet.proj1 |> TVarSet.elements in
  match sig_type ctx r with
  | None -> []
  | Some ty ->
      tyexpr_tvars ty
      |> List.filter_map (fun ((o_start, o_end), name) ->
        List.find_opt (fun v -> TVar.name v = name) vars
        |> Option.map (fun v -> {o_start; o_end; tvar = tvar_id ctx v}) )

(* The range of the type written in a [val] line, and of its parameter types
   when it is an arrow ([a -> b -> c]: [a] and [b]). *)
let sig_ranges ctx r =
  let rec strip : TyExpr.t -> TyExpr.t = function
    | TLoc (_, t)
    | TWhere (t, _) ->
        strip t
    | t -> t
  in
  let rec params : TyExpr.t -> (int * int) list = function
    | TArrow (TLoc (loc, _), rest) -> lex_range loc :: params (strip rest)
    | _ -> []
  in
  match sig_type ctx r with
  | Some (TLoc (loc, ty)) -> Some (lex_range loc, params (strip ty))
  | _ -> None

(* The position of [v] among the parameters of the definition of [def]. *)
let param_index ctx def v =
  match (binder_range def, binder_range v) with
  | Some d, (Some _ as r) ->
      Option.bind (List.assoc_opt d ctx.src.params) (fun ps -> List.find_index (fun p -> p = r) ps)
  | _ -> None

let group ctx callee args =
  let same (c, args', _) =
    c = callee && List.length args = List.length args' && List.for_all2 GTy.equiv args args'
  in
  match (callee, List.find_opt same ctx.groups) with
  | Some _, Some (_, _, g) -> g
  | _ ->
      let g = List.length ctx.groups in
      ctx.groups <- (callee, args, g) :: ctx.groups ;
      g

(* Names for the type variables of a definition without [val]. Its lens
   prints the scheme with ['a], ['b], ... in place of the inference variables;
   the same renaming applies to the body's types, so a variable reads the same
   in both. Variables the scheme dropped get the letters after those. *)
let lens_names (b : Main.inferred) =
  let tvs, _ = TyScheme.get b.ty in
  let names = ref (TVOp.shorten_names tvs) in
  let next = ref (List.length (MVarSet.elements1 tvs)) in
  let letter i =
    let c = String.make 1 (Char.chr ((i mod 26) + 97)) in
    if i < 26 then c else c ^ string_of_int (i / 26)
  in
  fun ty ->
    GTy.fv ty |> MVarSet.elements1
    |> List.iter (fun v ->
      if not (TVarSet.mem v (Subst.domain1 !names)) then begin
        let v' = TVar.mk KTemporary (Some (letter !next)) in
        incr next ;
        names := Subst.add1 v (TVar.typ v') !names
      end ) ;
    !names

(* Whether [b] has [val] lines. [Main] checks a draft with the definitions
   without signature, and marks it as not declared. *)
let declared (b : Main.inferred) = b.declared || Variable.get_sig_locations b.var <> []

let add ctx envs (b : Main.inferred) =
  ctx.sigs <- (b.var, b.sigs) :: ctx.sigs ;
  let declared = declared b in
  let display =
    if declared then
      Main.display_gty envs
    else
      let names = lens_names b in
      fun ty -> Main.display_gty ~names:(names ty) envs ty
  in
  let sig_texts = Main.signature envs b.sigs in
  (* The [val] lines, in the order of [b.sigs]. *)
  let sig_locs =
    if declared then
      Variable.get_sig_locations b.var |> List.rev |> List.filter_map range
    else
      []
  in
  (* The part of the [i]th [val] line to colour for a hover on [v]: the
     parameter's type when [v] is a parameter of the definition, else the
     whole type. *)
  let sig_range v = function
    | Some i ->
        Option.bind (List.nth_opt sig_locs i) (sig_ranges ctx)
        |> Option.map (fun (whole, params) ->
          let k = Option.bind v (param_index ctx b.var) in
          Option.value (Option.bind k (List.nth_opt params)) ~default:whole )
    | None -> None
  in
  let label = function
    | Some i when declared -> List.nth_opt sig_texts i
    | _ -> None
  in
  (* Hover types: per position, per derivation, the union of the types seen
     there (a node can be typed several times in one derivation). *)
  let at = Hashtbl.create 16 in
  let var_at = Hashtbl.create 16 in
  let note v (s, e) sig_index ty =
    Hashtbl.replace var_at (s, e) v ;
    let per_sig = Option.value (Hashtbl.find_opt at (s, e)) ~default:[] in
    let per_sig =
      match List.assoc_opt sig_index per_sig with
      | Some ty' -> (sig_index, GTy.cup ty ty') :: List.remove_assoc sig_index per_sig
      | None -> (sig_index, ty) :: per_sig
    in
    Hashtbl.replace at (s, e) per_sig
  in
  let marks = ref [] in
  let mark (m_start, m_end) ty =
    match tvar_ids ctx ty with
    | [] -> ()
    | tvars -> marks := {m_start; m_end; tvars} :: !marks
  in
  let calls = ref [] in
  b.derivations
  |> List.iter (fun (d : Main.derivation) ->
    Annotations.typings d
    |> List.iter (function
      | Annotations.Use (pos, v, ty) ->
          Option.iter
            (fun r ->
               note v r d.sig_index ty ;
               mark r ty ;
               occ ctx ~binder:false v r ;
               (* The binder of a variable from another definition. *)
               Option.iter (occ ctx ~binder:true v) (binder_range v) )
            (use_range ctx pos)
      | Binder (v, ty) when not (Variable.equal v b.var) ->
          Option.iter
            (fun r -> note v r d.sig_index ty ; mark r ty ; occ ctx ~binder:true v r)
            (binder_range v)
      | Binder _ -> ()
      | Call {pos; callee; args; result} -> (
          match range pos with
          | None -> ()
          | Some (c_start, c_end) ->
              mark (c_start, c_end) result ;
              (* Every argument, written in the source or not. *)
              let arg_types = List.map snd args in
              let args =
                List.filter_map
                  (fun (p, ty) -> Option.map (fun r -> mark r ty ; (r, ty)) (range p))
                  args
              in
              let callee_key =
                Option.bind callee (fun (v, _) ->
                  match (Variable.get_name v, binder_range v) with
                  | Some name, Some (s, _) -> Some (name, s)
                  | Some name, None -> Some (name, -1)
                  | None, _ -> None )
              in
              let instance =
                match callee with
                | None -> []
                | Some (_, s) ->
                    Subst.bindings1 s |> List.map (fun (v, ty) -> (var_name v, display (GTy.mk ty)))
              in
              (* An instance that only renames variables is left out: it
                 specializes nothing. *)
              let instances =
                match callee with
                | None -> []
                | Some (v, _) -> (
                    match List.find_opt (fun (v', _) -> Variable.equal v v') ctx.sigs with
                    | None -> []
                    | Some (_, sigs) ->
                        List.mapi (fun k o -> (k, o)) sigs
                        |> List.filter_map (fun (k, o) ->
                          match call_instance o arg_types result with
                          | Some inst when not (List.for_all (fun (_, ty) -> is_tvar ty) inst) ->
                              Some
                                ( k,
                                  List.map
                                    (fun (v, ty) -> (var_name v, display (GTy.mk ty) |> paren_tuple))
                                    inst
                                  |> List.sort compare )
                          | _ -> None ) )
              in
              calls :=
                {
                  c_start;
                  c_end;
                  callee = callee_key;
                  sig_index = d.sig_index;
                  args = List.map (fun ((s, e), ty) -> (s, e, display ty)) args;
                  result = display result;
                  instance;
                  instances;
                  group = group ctx callee_key (List.map snd args);
                }
                :: !calls ) ) ) ;
  let hovers =
    Hashtbl.fold
      (fun (h_start, h_end) per_sig hovers ->
         let per_sig = List.sort (fun (i, _) (j, _) -> compare i j) per_sig in
         let texts = List.map (fun (i, ty) -> (i, display ty)) per_sig in
         (* Every derivation, in [val] order, so that row [i] is the [i]th
            [val] line: a derivation that never typed this node did not reach
            it. *)
         let all = List.map (fun (d : Main.derivation) -> d.sig_index) b.derivations in
         let reached_by_all = List.for_all (fun i -> List.mem_assoc i texts) all in
         let body =
           match List.sort_uniq compare (List.map snd texts) with
           | [t] when reached_by_all -> Type t
           | _ ->
               let v = Hashtbl.find_opt var_at (h_start, h_end) in
               Overloads
                 {
                   rows =
                     List.map
                       (fun i ->
                          {
                            row_type = List.assoc_opt i texts;
                            sig_text = label i;
                            sig_range = sig_range v i;
                          } )
                       all;
                   union = display (GTy.disj (List.map snd per_sig));
                 }
         in
         {h_start; h_end; body} :: hovers )
      at []
  in
  (* The defined name itself: its final type, as in the lens. *)
  let hovers =
    match (binder_range b.var, Variable.get_name b.var) with
    | Some (h_start, h_end), Some name ->
        occ ctx ~binder:true b.var (h_start, h_end) ;
        {h_start; h_end; body = Type (name ^ " : " ^ Main.display envs b.ty)} :: hovers
    | _ -> hovers
  in
  (* The overloads of the [i]th [val] line. A complete signature's overloads
     are its lines. A draft's are its lines filled by each solution of its
     holes. *)
  let draft =
    List.exists
      (fun loc ->
         match sig_type ctx loc with
         | Some ty -> tyexpr_holes ty <> []
         | None -> false )
      sig_locs
  in
  let solutions = if draft then draft_solutions ctx envs display b.ty sig_locs else [] in
  let line_overloads i =
    if draft then
      List.filter_map (fun (_, lines) -> Option.map GTy.mk (List.nth_opt lines i)) solutions
    else
      Option.to_list (Option.map Signature.to_gty (List.nth_opt b.sigs i))
  in
  let hovers = draft_hole_hovers display solutions @ hovers in
  let tvar_occs =
    List.concat
      (List.mapi
         (fun i loc ->
            List.concat_map (fun o -> val_tvar_occs ctx o loc) (line_overloads i)
            |> List.sort_uniq compare )
         sig_locs )
  in
  ctx.acc <-
    {
      hovers = hovers @ ctx.acc.hovers;
      defns = {tvar_occs; marks = !marks} :: ctx.acc.defns;
      (* A node typed several times in one derivation gives identical calls. *)
      calls = List.rev_append (List.sort_uniq compare !calls) ctx.acc.calls;
      occs = [];
      fixes = ctx.acc.fixes;
    }

let add_fixes ctx fixes = ctx.acc <- {ctx.acc with fixes = fixes @ ctx.acc.fixes}
