(* Types of variables and calls, as plain data for hover and highlighting.

   A definition is checked once per derivation (one per [val] line, if any),
   and [Main] keeps each derivation; [Annotations] reads from it the type of
   every variable occurrence, binder and call. This module turns those into
   plain data (byte ranges, strings, integers) that the supervisor keeps and
   answers from, without the engine.

   Type variables are identified by integers, assigned per document. The
   builder shares variable objects by name, so ['a] in two [val] lines can be
   one variable: highlighting matches by this identity, within one
   definition. Only rigid variables (written by the user) get ids: those are
   the ones a [val] line can show. *)

open Mlsem_common
open Mlsem_types
open Mlsem_app

(* A variable occurrence or binder, with what its hover shows: a single type,
   or, when derivations differ, one row per derivation (type and the [val]
   signature it was checked against) followed by their union. *)
type overload_row = {
  row_type: string option;  (** [None]: this derivation never reaches the node *)
  sig_text: string option;
  sig_range: (int * int) option;  (** the [val] line, to colour in the editor *)
}

type hover_body =
  | Type of string
  (* A hole of a draft [val] line, as written ([_] or ['_a]), and the type it
     was resolved to. *)
  | Hole of {
      hole: string;
      value: string;
    }
  (* A hole of a line whose check gave several overloads, which disagree on
     it: per overload, its value ([None]: the line cannot be that overload). *)
  | Hole_per_overload of {
      hole: string;
      rows: (string * string option) list;
    }
  | Overloads of {
      rows: overload_row list;
      union: string;
    }

type hover = {
  h_start: int;
  h_end: int;
  body: hover_body;
}

(* An occurrence of a type variable in a [val] line. *)
type tvar_occ = {
  o_start: int;
  o_end: int;
  tvar: int;
}

(* Something in a definition's body whose type mentions type variables: a
   variable occurrence or binder, a call argument, or a whole call. *)
type mark = {
  m_start: int;
  m_end: int;
  tvars: int list;
}

type defn = {
  tvar_occs: tvar_occ list;
  marks: mark list;
}

(* A call site [f a1 ... an]. [group] is shared by the calls of the same
   callee whose argument types are equivalent. *)
type call = {
  c_start: int;
  c_end: int;
  callee: (string * int) option;  (** name and definition offset *)
  sig_index: int option;
  args: (int * int * string) list;
  result: string;
  instance: (string * string) list;  (** callee's type variable := type *)
  group: int;
}

(* Where a variable is bound or used, for highlighting its occurrences. [var]
   identifies the variable within the document. *)
type occ = {
  v_start: int;
  v_end: int;
  var: int;
  binder: bool;
}

type t = {
  hovers: hover list;
  defns: defn list;
  calls: call list;
  occs: occ list;
}

let empty = {hovers = []; defns = []; calls = []; occs = []}

let range pos =
  if pos = Position.dummy then
    None
  else
    Some
      ( Position.offset (Position.start_of_position pos),
        Position.offset (Position.end_of_position pos) )

let lex_range ((s, e) : Lexing.position * Lexing.position) = (s.pos_cnum, e.pos_cnum)

(* What the editor tooling needs from the parsed program. *)
type source = {
  sigs: ((int * int) * TyExpr.t) list;
    (** a [val] line's range and its type, as written (with locations) *)
  params: ((int * int) * (int * int) option list) list;
    (** a definition's name and its parameters' names, in order; [None]
          for a parameter that is a pattern *)
  uses: (int * int, unit) Hashtbl.t;
    (** variable occurrences written in the source, as opposed to ones
          generated by desugaring *)
}

let children : PAst.pexpr -> PAst.pexpr list =
 fun (_, e) ->
  match e with
  | Magic _
  | Const _
  | Var _
  | Enum _
  | Break
  | Continue ->
      []
  | NoGen e
  | Tag (_, e)
  | TagProj (e, _)
  | Suggest (_, _, e)
  | Lambda (_, _, e)
  | Declare (_, e)
  | TupleProj (e, _, _)
  | Hd e
  | Tl e
  | RecordProj (e, _)
  | TypeCast (e, _, _)
  | TypeCoerce (e, _, _)
  | VarAssign (_, e)
  | Return e ->
      [e]
  | LambdaRec l -> List.map (fun (_, _, e) -> e) l
  | Ite (e, _, e1, e2) -> [e; e1; e2]
  | App (a, b)
  | Let (_, a, b)
  | Cons (a, b)
  | Seq (a, b)
  | While (a, _, b) ->
      [a; b]
  | Tuple es
  | Alt es ->
      es
  | Record l -> List.map snd l
  | RecordUpdate (a, _, b) -> a :: Option.to_list b
  | PatMatch (e, l) -> e :: List.map snd l
  | Cond (e, _, e1, e2) -> e :: e1 :: Option.to_list e2

(* The parameters of a definition: its leading lambdas. A parameter that is a
   pattern is a lambda on a placeholder matched right away; when the pattern
   is a variable ([(x : t)]), that variable is the parameter. *)
let rec params_of ((_, e) : PAst.pexpr) =
  match e with
  | Lambda (name, _, body) -> (
      match (range (Position.position name), body) with
      | Some r, _ -> Some r :: params_of body
      | None, (_, PatMatch (_, [(PatVar (_, name), body)])) ->
          range (Position.position name) :: params_of body
      | None, (_, PatMatch (_, [(_, body)])) -> None :: params_of body
      | None, _ -> None :: params_of body )
  | _ -> []

let source (program : PAst.program) =
  let uses = Hashtbl.create 64 in
  let rec collect_uses ((_, e) as pe : PAst.pexpr) =
    ( match e with
    | Var name -> Option.iter (fun r -> Hashtbl.replace uses r ()) (range (Position.position name))
    | _ -> () ) ;
    List.iter collect_uses (children pe)
  in
  let sigs, params =
    List.fold_left
      (fun (sigs, params) (annot, elem) ->
         match (elem : PAst.element) with
         | SigDef (_, _, ty) -> (
             match range (Position.position annot) with
             | Some r -> ((r, ty) :: sigs, params)
             | None -> (sigs, params) )
         | Definitions defs ->
             List.fold_left
               (fun (sigs, params) (_, (_, name), e) ->
                  collect_uses e ;
                  match range (Position.position name) with
                  | Some r -> (sigs, (r, params_of e) :: params)
                  | None -> (sigs, params) )
               (sigs, params) defs
         | _ -> (sigs, params) )
      ([], []) program
  in
  {sigs; params; uses}

(* Per-document state while converting. *)
type ctx = {
  src: source;
  mutable tvar_ids: (TVar.t * int) list;
  mutable groups: ((string * int) option * GTy.t list * int) list;
  mutable var_ids: (Variable.t * int) list;
  mutable occs: occ list;
  mutable acc: t;
}

let create program =
  {src = source program; tvar_ids = []; groups = []; var_ids = []; occs = []; acc = empty}

(* A node is typed once per derivation, and some several times in one. *)
let finish ctx = {ctx.acc with occs = List.sort_uniq compare ctx.occs}

let var_id ctx v =
  match List.find_opt (fun (v', _) -> Variable.equal v v') ctx.var_ids with
  | Some (_, i) -> i
  | None ->
      let i = List.length ctx.var_ids in
      ctx.var_ids <- (v, i) :: ctx.var_ids ;
      i

let occ ctx ~binder v (v_start, v_end) =
  ctx.occs <- {v_start; v_end; var = var_id ctx v; binder} :: ctx.occs

let tvar_id ctx v =
  match List.find_opt (fun (v', _) -> TVar.equal v v') ctx.tvar_ids with
  | Some (_, i) -> i
  | None ->
      let i = List.length ctx.tvar_ids in
      ctx.tvar_ids <- (v, i) :: ctx.tvar_ids ;
      i

let tvar_ids ctx ty =
  GTy.fv ty |> MVarSet.proj1 |> TVarSet.elements
  |> List.filter (TVar.has_kind KNoInfer)
  |> List.map (tvar_id ctx)
  |> List.sort_uniq compare

let var_name v = TVar.prefix v ^ TVar.name v

(* The range of a variable occurrence, if it is written in the source:
   desugaring (pattern matching, loops, mutable variables) generates
   occurrences that either have no location or point at something else. *)
let use_range ctx pos =
  Option.bind (range pos) (fun r -> if Hashtbl.mem ctx.src.uses r then Some r else None)

(* Where the name of a bound variable is written. *)
let binder_range v = range (Variable.get_name_location v)

let rec tyexpr_children : TyExpr.t -> TyExpr.t list = function
  | TDyn
  | TVar _
  | TRowVar _
  | TBase _
  | TEnum _
  | TCustom _ ->
      []
  | TApp (_, ts)
  | TTuple ts ->
      ts
  | TTag (_, t)
  | TOption t
  | TNeg t
  | TRecProj (t, _)
  | TTagProj (t, _)
  | TLoc (_, t) ->
      [t]
  | TRecord (fields, tail) -> tail :: List.map snd fields
  | TSList re -> regexp_children re
  | TCons (a, b)
  | TArrow (a, b)
  | TCup (a, b)
  | TCap (a, b)
  | TDiff (a, b) ->
      [a; b]
  | TWhere (t, defs) -> t :: List.map (fun (_, _, t) -> t) defs
  | TRecUpd (t, fields) -> t :: List.map snd fields

and regexp_children : TyExpr.regexp -> TyExpr.t list = function
  | Epsilon -> []
  | Symbol t -> [t]
  | Union rs
  | Concat rs ->
      List.concat_map regexp_children rs
  | Star r
  | Plus r
  | Option r ->
      regexp_children r

(* Located type variables written in [ty]. *)
let rec tyexpr_tvars (ty : TyExpr.t) =
  match ty with
  | TLoc (loc, TVar (_, name)) -> [(lex_range loc, name)]
  | _ -> List.concat_map tyexpr_tvars (tyexpr_children ty)

(* The type written in the [val] line at [r]. *)
let sig_type ctx r = List.assoc_opt r ctx.src.sigs

(* Located holes of a draft [val] line: its weak type variables, written [_]
   (named [_holeN] by the parser) or ['_a]. *)
let rec tyexpr_holes (ty : TyExpr.t) =
  match ty with
  | TLoc (loc, TVar (KInfer, name)) -> [(lex_range loc, name)]
  | _ -> List.concat_map tyexpr_holes (tyexpr_children ty)

(* What each hole of the [val] line at [r] is for the line to be [overload]:
   tallying the line's type, holes included, against it, in both directions.
   [None] when nothing fits. *)
let hole_values ctx envs display overload r =
  match Option.map tyexpr_holes (sig_type ctx r) with
  | None
  | Some [] ->
      None
  | Some holes -> (
      let benv, _, _, _, _ = envs in
      let draft, _ = Signature.build benv (Option.get (sig_type ctx r)) in
      let d = Signature.to_gty draft |> GTy.ub in
      let o = Signature.to_gty overload |> GTy.ub in
      (* The resolved type is fixed: only the holes are solved for. Its
         variables are rigid already (generalized, then renamed rigid by
         [Signature.of_tyscheme]); a weak one would be made rigid too. *)
      let o =
        let w = TVOp.vars o |> MVarSet.proj1 |> TVarSet.filter (TVar.has_kind KInfer) in
        Subst.apply (TVOp.refresh ~kind:KNoInfer (MVarSet.of_set1 w)) o
      in
      (* The holes: the draft's weak variables, not its rigid ones. *)
      let weak =
        TVOp.vars d |> MVarSet.proj1 |> TVarSet.elements |> List.filter (TVar.has_kind KInfer)
      in
      match TVOp.tally (TVOp.all_vars KNoInfer) [(d, o); (o, d)] with
      | [] -> None
      | s :: _ ->
          (* The most general solution can leave weak variables, the holes'
             own among them ([_hole := ('a & int) | (_hole \ int)] when the
             hole is intersected with [int]). Any choice for them is a
             solution, but one choice for the whole line, so that the holes
             agree:
             - those in the line are chosen by their polarity in it, as when
               simplifying a signature ([empty] where only positive, [any]
               where only negative); one there both ways is a variable of the
               signature, made a rigid one;
             - those not in the line do not change it: [empty]. *)
          let mono = TVOp.all_vars KNoInfer in
          let weak_of t =
            TVOp.vars t |> MVarSet.proj1 |> TVarSet.elements |> List.filter (TVar.has_kind KInfer)
          in
          let clean =
            TVOp.clean_subst' ~pos1:Ty.empty ~neg1:Ty.any ~pos2:Row.empty ~neg2:Row.any mono
              [Subst.apply s d]
          in
          let line = Subst.apply clean (Subst.apply s d) in
          let rigid =
            TVOp.refresh ~kind:KNoInfer (MVarSet.of_set1 (TVarSet.of_list (weak_of line)))
          in
          let resolve t = Subst.apply rigid (Subst.apply clean (Subst.apply s t)) in
          let rest =
            List.concat_map (fun v -> weak_of (resolve (TVar.typ v))) weak
            |> List.sort_uniq TVar.compare
            |> List.map (fun w -> (w, Ty.empty))
            |> Subst.of_list1
          in
          let resolve t = Subst.apply rest (resolve t) in
          (* Only shown if filling the holes gives back the resolved type. *)
          let filled = resolve d in
          if not (Ty.leq filled o && Ty.leq o filled) then
            None
          else
            Some
              (List.filter_map
                 (fun (range, name) ->
                    List.find_opt (fun v -> TVar.name v = name) weak
                    |> Option.map (fun v ->
                      let shown =
                        if String.starts_with ~prefix:"_hole" name then "_" else "'" ^ name
                      in
                      let value = resolve (TVar.typ v) |> GTy.mk |> display in
                      (* A tuple is printed without parentheses. *)
                      let value =
                        if String.contains value ',' && value.[0] <> '(' then
                          "(" ^ value ^ ")"
                        else
                          value
                      in
                      (range, shown, value) ) )
                 holes ) )

(* What each hole of the [val] line at [r] became, as hovers. [overloads] is
   the type the line's own check gave: several when the body is overloaded,
   and then a hole has one value only if every overload gives it the same;
   otherwise its hover lists the value for each overload, and it cannot be
   filled. *)
let hole_hovers ctx envs display overloads r =
  let per = List.map (fun o -> (o, hole_values ctx envs display o r)) overloads in
  match per with
  | [(_, None)]
  | [] ->
      []
  | [(_, Some values)] ->
      List.map
        (fun ((h_start, h_end), hole, value) -> {h_start; h_end; body = Hole {hole; value}})
        values
  | _ -> (
      (* The holes, from whichever overload gave values. *)
      match List.find_map snd per with
      | None -> []
      | Some holes ->
          List.mapi
            (fun i ((h_start, h_end), hole, _) ->
               let value_in = Option.map (fun vs -> (fun (_, _, v) -> v) (List.nth vs i)) in
               let values = List.map (fun (_, vs) -> value_in vs) per in
               let body =
                 match List.sort_uniq compare values with
                 | [Some value] -> Hole {hole; value}
                 | _ ->
                     Hole_per_overload
                       {
                         hole;
                         rows =
                           List.map2 (fun (o, _) v -> (display (Signature.to_gty o), v)) per values;
                       }
               in
               {h_start; h_end; body} )
            holes )

(* Occurrences of the overload's type variables in its [val] line. *)
let val_tvar_occs ctx overload r =
  let vars = Signature.to_gty overload |> GTy.fv |> MVarSet.proj1 |> TVarSet.elements in
  match sig_type ctx r with
  | None -> []
  | Some ty ->
      tyexpr_tvars ty
      |> List.filter_map (fun ((o_start, o_end), name) ->
        List.find_opt (fun v -> TVar.name v = name) vars
        |> Option.map (fun v -> {o_start; o_end; tvar = tvar_id ctx v}) )

(* The range of the type written in a [val] line, and of its parameter types
   when it is an arrow ([a -> b -> c]: [a] and [b]). *)
let sig_ranges ctx r =
  let rec strip : TyExpr.t -> TyExpr.t = function
    | TLoc (_, t)
    | TWhere (t, _) ->
        strip t
    | t -> t
  in
  let rec params : TyExpr.t -> (int * int) list = function
    | TArrow (TLoc (loc, _), rest) -> lex_range loc :: params (strip rest)
    | _ -> []
  in
  match sig_type ctx r with
  | Some (TLoc (loc, ty)) -> Some (lex_range loc, params (strip ty))
  | _ -> None

(* The position of [v] among the parameters of the definition of [def]. *)
let param_index ctx def v =
  match (binder_range def, binder_range v) with
  | Some d, (Some _ as r) ->
      Option.bind (List.assoc_opt d ctx.src.params) (fun ps -> List.find_index (fun p -> p = r) ps)
  | _ -> None

let group ctx callee args =
  let same (c, args', _) =
    c = callee && List.length args = List.length args' && List.for_all2 GTy.equiv args args'
  in
  match (callee, List.find_opt same ctx.groups) with
  | Some _, Some (_, _, g) -> g
  | _ ->
      let g = List.length ctx.groups in
      ctx.groups <- (callee, args, g) :: ctx.groups ;
      g

(* Names for the type variables of a definition without [val]. Its lens
   prints the scheme with ['a], ['b], ... in place of the inference variables;
   the same renaming applies to the body's types, so a variable reads the same
   in both. Variables the scheme dropped get the letters after those. *)
let lens_names (b : Main.inferred) =
  let tvs, _ = TyScheme.get b.ty in
  let names = ref (TVOp.shorten_names tvs) in
  let next = ref (List.length (MVarSet.elements1 tvs)) in
  let letter i =
    let c = String.make 1 (Char.chr ((i mod 26) + 97)) in
    if i < 26 then c else c ^ string_of_int (i / 26)
  in
  fun ty ->
    GTy.fv ty |> MVarSet.elements1
    |> List.iter (fun v ->
      if not (TVarSet.mem v (Subst.domain1 !names)) then begin
        let v' = TVar.mk KTemporary (Some (letter !next)) in
        incr next ;
        names := Subst.add1 v (TVar.typ v') !names
      end ) ;
    !names

let add ctx envs (b : Main.inferred) =
  let display =
    if b.declared then
      Main.display_gty envs
    else
      let names = lens_names b in
      fun ty -> Main.display_gty ~names:(names ty) envs ty
  in
  let sig_texts = Main.signature envs b.sigs in
  (* The [val] lines, in the order of [b.sigs]. *)
  let sig_locs =
    if b.declared then
      Variable.get_sig_locations b.var |> List.rev |> List.filter_map range
    else
      []
  in
  (* The part of the [i]th [val] line to colour for a hover on [v]: the
     parameter's type when [v] is a parameter of the definition, else the
     whole type. *)
  let sig_range v = function
    | Some i ->
        Option.bind (List.nth_opt sig_locs i) (sig_ranges ctx)
        |> Option.map (fun (whole, params) ->
          let k = Option.bind v (param_index ctx b.var) in
          Option.value (Option.bind k (List.nth_opt params)) ~default:whole )
    | None -> None
  in
  let label = function
    | Some i when b.declared -> List.nth_opt sig_texts i
    | _ -> None
  in
  (* Hover types: per position, per derivation, the union of the types seen
     there (a node can be typed several times in one derivation). *)
  let at = Hashtbl.create 16 in
  let var_at = Hashtbl.create 16 in
  let note v (s, e) sig_index ty =
    Hashtbl.replace var_at (s, e) v ;
    let per_sig = Option.value (Hashtbl.find_opt at (s, e)) ~default:[] in
    let per_sig =
      match List.assoc_opt sig_index per_sig with
      | Some ty' -> (sig_index, GTy.cup ty ty') :: List.remove_assoc sig_index per_sig
      | None -> (sig_index, ty) :: per_sig
    in
    Hashtbl.replace at (s, e) per_sig
  in
  let marks = ref [] in
  let mark (m_start, m_end) ty =
    match tvar_ids ctx ty with
    | [] -> ()
    | tvars -> marks := {m_start; m_end; tvars} :: !marks
  in
  let calls = ref [] in
  b.derivations
  |> List.iter (fun (d : Main.derivation) ->
    Annotations.typings d
    |> List.iter (function
      | Annotations.Use (pos, v, ty) ->
          Option.iter
            (fun r ->
               note v r d.sig_index ty ;
               mark r ty ;
               occ ctx ~binder:false v r ;
               (* The binder of a variable from another definition. *)
               Option.iter (occ ctx ~binder:true v) (binder_range v) )
            (use_range ctx pos)
      | Binder (v, ty) when not (Variable.equal v b.var) ->
          Option.iter
            (fun r -> note v r d.sig_index ty ; mark r ty ; occ ctx ~binder:true v r)
            (binder_range v)
      | Binder _ -> ()
      | Call {pos; callee; args; result} -> (
          match range pos with
          | None -> ()
          | Some (c_start, c_end) ->
              mark (c_start, c_end) result ;
              let args =
                List.filter_map
                  (fun (p, ty) -> Option.map (fun r -> mark r ty ; (r, ty)) (range p))
                  args
              in
              let callee_key =
                Option.bind callee (fun (v, _) ->
                  match (Variable.get_name v, binder_range v) with
                  | Some name, Some (s, _) -> Some (name, s)
                  | Some name, None -> Some (name, -1)
                  | None, _ -> None )
              in
              let instance =
                match callee with
                | None -> []
                | Some (_, s) ->
                    Subst.bindings1 s |> List.map (fun (v, ty) -> (var_name v, display (GTy.mk ty)))
              in
              calls :=
                {
                  c_start;
                  c_end;
                  callee = callee_key;
                  sig_index = d.sig_index;
                  args = List.map (fun ((s, e), ty) -> (s, e, display ty)) args;
                  result = display result;
                  instance;
                  group = group ctx callee_key (List.map snd args);
                }
                :: !calls ) ) ) ;
  let hovers =
    Hashtbl.fold
      (fun (h_start, h_end) per_sig hovers ->
         let per_sig = List.sort (fun (i, _) (j, _) -> compare i j) per_sig in
         let texts = List.map (fun (i, ty) -> (i, display ty)) per_sig in
         (* Every derivation, in [val] order, so that row [i] is the [i]th
            [val] line: a derivation that never typed this node did not reach
            it. *)
         let all = List.map (fun (d : Main.derivation) -> d.sig_index) b.derivations in
         let reached_by_all = List.for_all (fun i -> List.mem_assoc i texts) all in
         let body =
           match List.sort_uniq compare (List.map snd texts) with
           | [t] when reached_by_all -> Type t
           | _ ->
               let v = Hashtbl.find_opt var_at (h_start, h_end) in
               Overloads
                 {
                   rows =
                     List.map
                       (fun i ->
                          {
                            row_type = List.assoc_opt i texts;
                            sig_text = label i;
                            sig_range = sig_range v i;
                          } )
                       all;
                   union = display (GTy.disj (List.map snd per_sig));
                 }
         in
         {h_start; h_end; body} :: hovers )
      at []
  in
  (* The defined name itself: its final type, as in the lens. *)
  let hovers =
    match (binder_range b.var, Variable.get_name b.var) with
    | Some (h_start, h_end), Some name ->
        occ ctx ~binder:true b.var (h_start, h_end) ;
        {h_start; h_end; body = Type (name ^ " : " ^ Main.display envs b.ty)} :: hovers
    | _ -> hovers
  in
  (* The overloads of the [i]th [val] line. A complete signature's overloads
     are its lines. A draft's are what each line's check gave, which can be
     several for one line (an overloaded body), so they are taken from that
     line's derivation, not by position. *)
  let draft =
    List.exists
      (fun loc ->
         match sig_type ctx loc with
         | Some ty -> tyexpr_holes ty <> []
         | None -> false )
      sig_locs
  in
  let line_overloads i =
    if draft then
      match
        List.find_opt (fun (d : Main.derivation) -> d.sig_index = Some i) b.derivations
      with
      | Some d -> d.resolved
      | None -> []
    else
      Option.to_list (List.nth_opt b.sigs i)
  in
  let hovers =
    List.concat
      (List.mapi (fun i loc -> hole_hovers ctx envs display (line_overloads i) loc) sig_locs)
    @ hovers
  in
  let tvar_occs =
    List.concat
      (List.mapi
         (fun i loc ->
            List.concat_map (fun o -> val_tvar_occs ctx o loc) (line_overloads i)
            |> List.sort_uniq compare )
         sig_locs )
  in
  ctx.acc <-
    {
      hovers = hovers @ ctx.acc.hovers;
      defns = {tvar_occs; marks = !marks} :: ctx.acc.defns;
      (* A node typed several times in one derivation gives identical calls. *)
      calls = List.rev_append (List.sort_uniq compare !calls) ctx.acc.calls;
      occs = [];
    }
